#!/usr/bin/env python3
"""wow-waypoint: WoW character tracker for Claude Code. Stdlib only.

Characters
  add "<First Last>" [--region us] [--version forever] [--watch] [--group NAME] [--role tank,dps] [--main] [--source ID]
  main [<char>]                    show or change the primary character: the user's favorite, the default everywhere.
                                   Long-lived; change it only when the favorite changes, never to switch for a session
  set <char> key=value ...         edit a character entry (roles=tank,dps  main=true  version=era  group=...)
  list | where
  update [--force] [--quiet] [--hook]   snapshot everyone (throttled to once per 20h each); --hook adds Claude's standing instructions
  gear <char> | diff <char> [--since DATE] | milestones <char>
  doctor [<char>]                  check that the armory site still parses; saves the page on failure
Activity
  log <char> "text"                append to <char>/activity.md ("?" prefix = open question; "=== recapped ===" closes a recap window)
  pending                          activity and open questions not yet in a journal entry
  chats [--since DATE]             your own questions from this project's Claude Code transcripts
Group
  party [--group NAME] [--since DATE]   everyone at a glance; --since = what each character did in that window
Instances
  brief [<char>] <instance> [--role tank|heal|dps]   role briefing from instance notes (exit 2 = no notes yet)
Views
  dashboard [--out PATH] [--group NAME] [--open]
  statusline [--all] [--ascii] [--prefix-cmd CMD]   reads Claude Code's status JSON on stdin
  focus <char> [--session ID] | focus --clear   this session's character: pins the status line (to one session with
                                   --session) without touching main; --clear goes back to main
  install-statusline [--chain]     write the status line into this workspace's .claude/settings.json
Setup
  setup-status                     what /wow-init has set up so far
  profile | profile set key=value ...   player profile (version, realmType, playstyle=a,b, hoursPerWeek, goals=a,b, ...)

Data lives in YOUR workspace (never this repo): $WOWCHAR_HOME, else $CLAUDE_PROJECT_DIR, else the nearest
folder above cwd holding notes/characters/, else cwd. Per character: notes/characters/<slug>/
  latest.json (normalized snapshot) · history.jsonl · summary.md (generated) · activity.md · journal.md (/recap) · plan.md (/plan)
"""
