def cmd_focus(args):
    """focus <char> [--session ID] pins the status line (to one session if given); focus --clear unpins.

    focus = the character this session is about. It never changes main; once cleared (or in another session),
    the status line and the default go back to main."""
    path = core.BASE / ".focus.json"
    if "--clear" in args:
        path.unlink(missing_ok=True)
        p = core.primary()
        print("status line focus cleared (back to " + (f"main: {p['name']})" if p else "most recently played)"))
        return
    c = need_char(positional(args)[0] if positional(args) else None)
    sid = opt(args, "--session")
    core.write_text(path, json.dumps({"slug": c["slug"], "session_id": sid}) + "\n")
    print(f"status line pinned to {c['name']}" + (f" for session {sid}" if sid else " (all sessions until focus --clear)")
          + "; main is unchanged")


