def cmd_doctor(args):
    pos = positional(args)
    chars = [need_char(pos[0])] if pos else core.load_config()
    if not chars:
        sys.exit("no tracked characters")
    ok_all = True
    seen = set()
    for c in chars:
        try:
            sid, (steps, page) = sources.diagnose(c, core.data("sources"))
        except sources.Unsupported as e:
            print(f"{c['slug']}: {e}")
            continue
        if sid in seen and not pos:
            continue  # one check per site is enough unless a character was named
        seen.add(sid)
        print(f"{c['slug']} via {sid}:")
        for ok, label, detail in steps:
            print(f"  {'✓' if ok else '✗'} {label}: {detail}")
        bad = [s for s in steps if not s[0]]
        if bad:
            ok_all = False
            if bad[0][1] != "fetch":
                core.record_health(c["slug"], [f"{b[1]}: {b[2]}" for b in bad])
            if page:
                p = core.BASE / ".debug" / f"{c['slug']}-{datetime.now().strftime('%Y%m%d-%H%M%S')}.html"
                core.write_text(p, page)
                print(f"  saved page for debugging: {p}")
        else:
            core.record_health(c["slug"], [])
    settings = core.read_json(core.ROOT / ".claude" / "settings.json", {}) or {}
    cmd = (settings.get("statusLine") or {}).get("command", "")
    if "wowchar.py" in cmd:
        m = re.search(r'"([^"]*wowchar\.py)"', cmd)
        if m and not Path(m.group(1)).exists():
            ok_all = False
            print(f"✗ status line points at a missing script ({m.group(1)}); run install-statusline again")
        else:
            print("✓ status line script path ok")
    sys.exit(0 if ok_all else 1)


