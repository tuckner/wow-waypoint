def cmd_install_statusline(args):
    path = core.ROOT / ".claude" / "settings.json"
    core.guard(path)
    settings = core.read_json(path, {}) if path.exists() else {}
    if settings is None:
        sys.exit(f"{path} isn't valid JSON; fix it first")
    ours = f'python3 "{core.SCRIPT}" statusline'
    existing = (settings.get("statusLine") or {}).get("command")
    if existing and "wowchar.py" not in existing:
        if "--chain" not in args:
            print(f"A status line already exists: {existing}\nNot overwriting. Re-run with --chain to show it first and append ours.")
            sys.exit(1)
        ours += " --prefix-cmd " + shlex.quote(existing)
    elif existing and "--prefix-cmd" in existing:
        ours += " --prefix-cmd " + existing.split("--prefix-cmd", 1)[1].strip()
    settings["statusLine"] = {"type": "command", "command": ours}
    core.write_text(path, json.dumps(settings, indent=2) + "\n")
    print(f"status line installed in {path}: {ours}\nIt shows from the next Claude Code session in this folder.")


