def instance_window(levels, factions, version="forever"):
    lo, hi = min(levels), max(levels)
    fs = {f for f in factions if f}
    return [i for i in core.rules("instances", version)
            if i["type"] == "dungeon" and lo >= i["min"] - 3 and hi <= i["max"] and (not i.get("faction") or fs <= {i["faction"]})]


def cmd_party(args):
    group = opt(args, "--group")
    chars = [c for c in core.load_config() if not group or c.get("group") == group or not c.get("watch")]
    rows = []
    for c in chars:
        h = core.history(c["slug"])
        if h:
            rows.append((c, h))
    if not rows:
        sys.exit("no characters with snapshots")
    since = opt(args, "--since")
    if since or "--since" in args:
        since = since or (datetime.now() - timedelta(days=7)).strftime("%Y-%m-%d")
        print(f"Progress since {since}:")
        for c, h in rows:
            before = [s for s in h if s["at"][:10] < since]
            base = before[-1] if before else h[0]
            d = core.diff(base, h[-1])
            star = "★ " if not c.get("watch") else ""
            print(f"- {star}{h[-1]['name']} (lvl {base['level']} → {h[-1]['level']}): " + ("; ".join(d) if d else "no changes"))
        return
    print("| | Name | Class | Lvl | iLvl | Pace (lvl/day) | +5 levels in | Last login | Professions | Weakest |")
    print("|---|---|---|---|---|---|---|---|---|---|")
    for c, h in rows:
        cur = h[-1]
        p = core.pace(h)
        eta = core.eta_days(h, 5)
        weak = sorted(core.gear(c["slug"]).items(), key=lambda kv: kv[1]["ilvl"] or 0)[:3]
        print(f"| {'★' if not c.get('watch') else ''} | {cur['name']} | {cur.get('class')} | {cur['level']} | {cur.get('itemLevel')} | "
              f"{p['levels_per_day'] if p else '—'} | {f'~{eta}d' if eta else '—'} | {(cur.get('lastLogin') or '?')[:10]} | "
              f"{', '.join(f'{k} {v}' for k, v in cur['professions'].items())} | {', '.join(s + ' ' + str(i['ilvl']) for s, i in weak)} |")
    levels = [h[-1]["level"] for _, h in rows]
    factions = [h[-1].get("faction") for _, h in rows]
    fit = instance_window(levels, factions)
    print(f"\nShared level window: {min(levels)}–{max(levels)}. Dungeons that fit everyone: "
          + (", ".join(f"{i['name']} ({i['min']}–{i['max']})" for i in fit) or "none — the spread is too wide"))
    med = sorted(levels)[len(levels) // 2]
    off = [f"{h[-1]['name']} ({h[-1]['level']})" for _, h in rows if abs(h[-1]["level"] - med) > 3]
    if off:
        print(f"More than 3 levels from the median ({med}): " + ", ".join(off))


