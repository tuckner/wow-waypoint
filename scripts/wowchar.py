# ---------- arg helpers ----------

def opt(args, name, default=None):
    if name in args:
        i = args.index(name)
        if i + 1 < len(args):
            return args[i + 1]
    return default


def positional(args, with_values=("--region", "--version", "--group", "--role", "--source", "--since", "--out", "--prefix-cmd", "--session")):
    out, skip = [], False
    for i, a in enumerate(args):
        if skip:
            skip = False
            continue
        if a in with_values:
            skip = True
            continue
        if a.startswith("--"):
            continue
        out.append(a)
    return out


def need_char(key):
    c = core.find_char(key) if key else None
    if not c:
        sys.exit(f"unknown character {key!r}; tracked: " + ", ".join(x["slug"] for x in core.load_config()))
    return c


def default_char():
    rows = [(c, (core.history(c["slug"], tail=8000) or [{}])[-1]) for c in core.owned()]
    rows = [r for r in rows if r[1]]
    if not rows:
        sys.exit("no tracked characters with snapshots; run /wow-init or `add` first")
    if (p := core.primary([r[0] for r in rows])):
        return p
    return max(rows, key=lambda r: r[1].get("lastLogin") or "")[0]


