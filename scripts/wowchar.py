def cmd_log(args):
    if len(args) < 2:
        sys.exit('usage: log <char> "text"')
    c = need_char(args[0])
    if c.get("watch"):
        sys.exit(f"{c['slug']} is a watched character; activity is only logged for your own characters")
    text = " ".join(args[1:]).strip()
    a = core.char_dir(c["slug"]) / "activity.md"
    if not a.exists():
        a.write_text(f"# {c['slug']} — running activity log\n\nOne line per thing learned in chat. `?` = open question to ask; replace with the answer once known. /recap folds these into journal.md.\n\n")
    with a.open("a") as f:
        f.write(f"- {datetime.now().strftime('%Y-%m-%d %H:%M')} {text}\n")
    print(f"logged to {a.relative_to(core.ROOT)}")


def pending_report():
    out = []
    for c in core.owned():
        since = core.last_recap(c["slug"])
        lines = core.activity(c["slug"])
        marks = [i for i, l in enumerate(lines) if "=== recapped ===" in l]
        new = [l for l in lines[(marks[-1] + 1 if marks else 0):] if "?" != l[19:20]]
        qs = core.open_questions(c["slug"])
        if new or qs:
            out.append(f"{c['name']} (last recap {since}): {len(new)} new activity notes"
                       + "".join("\n  " + l[2:] for l in new[-8:] if l not in qs)
                       + "".join("\n  OPEN QUESTION " + l[2:] for l in qs))
    return out


def cmd_pending(_):
    print("\n".join(pending_report()) or "Nothing pending.")


def cmd_chats(args):
    since = opt(args, "--since", "0000")
    proj = Path.home() / ".claude" / "projects" / re.sub(r"[^A-Za-z0-9]", "-", str(core.ROOT))
    rows = []
    for f in proj.glob("*.jsonl"):
        for line in f.open():
            try:
                o = json.loads(line)
            except ValueError:
                continue
            if o.get("type") != "user" or o.get("isMeta"):
                continue
            c = o.get("message", {}).get("content")
            if isinstance(c, list):
                c = " ".join(x.get("text", "") for x in c if isinstance(x, dict) and x.get("type") == "text")
            if not isinstance(c, str) or not c.strip() or c.lstrip().startswith("<") or "session is being continued" in c:
                continue
            t = core.parse_time(o["timestamp"]).astimezone()
            if t.strftime("%Y-%m-%d") >= since:
                rows.append((t, " ".join(c.split())[:300]))
    for t, c in sorted(rows):
        print(t.strftime("%Y-%m-%d %H:%M"), c)


