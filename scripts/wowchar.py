def write_summary(slug, char=None):
    snaps = core.history(slug)
    n = core.latest(slug)
    if not snaps or not n:
        return
    char = char or core.find_char(slug) or {}
    version = core.version_of(char)
    cur, first = snaps[-1], snaps[0]
    items = core.gear(slug)
    weakest = sorted(items.items(), key=lambda kv: kv[1]["ilvl"] or 0)[:5]
    empty = [s for s in core.SLOTS if s not in items and s != "Off Hand"]
    p = core.pace(snaps)
    tag = " (watched friend)" if char.get("watch") else ""
    L = [f"_Generated by wow-waypoint — {datetime.now().strftime('%Y-%m-%d %H:%M')}. Do not edit; see journal.md / plan.md._", "",
         f"# {cur['name']} — level {cur['level']} {cur['race']} {cur['class']} ({cur['faction']}){tag}", "",
         f"- {core.version_info(char).get('label', version)} · {n.get('realmType') or '?'} realm · source {n.get('source', 'wowfio')}"
         + (f" · guild {n['guild']}" if n.get("guild") else "") + (f" · roles {', '.join(char['roles'])}" if char.get("roles") else ""),
         f"- Snapshot {cur['at'][:10]} · last login {(cur.get('lastLogin') or '?')[:10]} · item level {cur['itemLevel']} · quests {cur['quests']} · HKs {cur['kills']}",
         f"- Tracking since {first['at'][:10]} (level {first['level']}, {first['quests']} quests)",
         "- Pace (last 7d): " + (f"{p['levels_per_day']} levels/day, {p['quests_per_day']} quests/day over {p['days']}d" if p else "not enough history yet"),
         "- Talents: " + ", ".join(f"{k} {v}" for k, v in cur["talents"].items()),
         "  - " + "; ".join(f"{t}: " + ", ".join(f"{k.replace('_', ' ')} {r}" for k, r in ranks.items()) for t, ranks in cur["talentRanks"].items()),
         "- Professions: " + ", ".join(f"{k} {v}" for k, v in cur["professions"].items()),
         "- Reputation: " + ", ".join(f"{k} {v}" for k, v in cur["reps"].items()),
         "- Stats: " + ", ".join(f"{k} {v}" for k, v in cur["stats"].items()),
         "", "## Gear (weakest first by item level)",
         "| Slot | Item | iLvl | Req | Quality | Stats | Enchant |", "|---|---|---|---|---|---|---|"]
    for slot, i in sorted(items.items(), key=lambda kv: kv[1]["ilvl"] or 0):
        L.append(f"| {slot} | {i['name']} | {i['ilvl']} | {i['req'] or ''} | {i['quality']} | {', '.join(i['stats'])} | {i['enchant'] or ''} |")
    L += ["", "- Empty slots: " + (", ".join(empty) or "none"),
          "- Needs repair (<35% durability): " + (", ".join(f"{s} {i['durability']}" for s, i in items.items() if core.low_durability(i)) or "none"),
          "- Upgrade candidates: " + ", ".join(f"{s} ({i['name']}, iLvl {i['ilvl']})" for s, i in weakest)]
    up = milestones.upcoming(cur.get("class"), cur["level"], 2, version)
    nudges = milestones.profession_nudges(cur.get("professions"), cur["level"], version)
    L += ["", "## Upcoming (next 2 levels)"]
    L += [f"- {e['level']}: {e['what']}" + (" (verify on Forever)" if e.get("verify") else "") for e in up] or ["- nothing listed"]
    L += [f"- {x['what']}" for x in nudges]
    L += ["", "## Change log"]
    changes = [f"- **{b['at'][:10]}** (lvl {b['level']}): " + "; ".join(d) for a, b in zip(snaps, snaps[1:]) if (d := core.diff(a, b))]
    L += (changes[::-1][:30] or ["- (no changes recorded yet)"]) + [""]
    core.write_text(core.BASE / slug / "summary.md", "\n".join(L))


def store_snapshot(char, norm):
    slug = char["slug"]
    d = core.char_dir(slug)
    (d / "latest.json").write_text(json.dumps(norm, indent=1))
    snap = core.compact(norm)
    prev = (core.history(slug) or [None])[-1]
    with (d / "history.jsonl").open("a") as f:
        f.write(json.dumps(snap) + "\n")
    write_summary(slug, char)
    return snap, (core.diff(prev, snap) if prev else ["first snapshot"])


def fetch_one(char):
    """Fetch, record parse health, store. -> (snap, diff, problems). Raises sources.SourceError subclasses."""
    norm, problems = sources.fetch(char, core.data("sources"))
    core.record_health(char["slug"], problems)
    return store_snapshot(char, norm) + (problems,)


