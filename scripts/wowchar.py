def cmd_diff(args):
    c = need_char(positional(args)[0] if positional(args) else None)
    since = opt(args, "--since")
    snaps = core.history(c["slug"])
    if not snaps:
        sys.exit(f"no history for {c['slug']}")
    base = snaps[0]
    if since:
        before = [s for s in snaps if s["at"][:10] < since]
        base = before[-1] if before else snaps[0]
    cur = snaps[-1]
    print(f"{cur['name']}: {base['at'][:10]} → {cur['at'][:10]}")
    print("\n".join("- " + d for d in core.diff(base, cur)) or "- no changes")
    per = [f"  {b['at'][:10]}: " + "; ".join(d) for a, b in zip(snaps, snaps[1:]) if b["at"] > base["at"] and (d := core.diff(a, b))]
    if per:
        print("By day:\n" + "\n".join(per))


