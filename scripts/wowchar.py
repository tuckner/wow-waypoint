def cmd_update(args):
    force, quiet, hook = "--force" in args, "--quiet" in args, "--hook" in args
    chars = core.load_config()
    if hook and not chars:
        return  # plugin installed but nothing tracked in this folder: stay silent
    report = []
    for c in chars:
        h = core.history(c["slug"], tail=8000)
        if h and not force and (core.now() - core.parse_time(h[-1]["at"])).total_seconds() < core.THROTTLE_HOURS * 3600:
            continue
        try:
            snap, d, problems = fetch_one(c)
            if d and not c.get("watch"):
                report.append(f"{snap['name']} (lvl {snap['level']}): " + "; ".join(d))
            if problems:
                report.append(f"{c['slug']}: parsed with problems ({'; '.join(problems)})")
        except sources.Unsupported as e:
            report.append(f"{c['slug']}: {e}")
        except sources.NetworkError as e:
            report.append(f"{c['slug']}: fetch failed, site unreachable ({e}); will retry next session")
        except sources.ParseError as e:
            core.record_health(c["slug"], [str(e)])
            report.append(f"{c['slug']}: could not read the armory page ({e})")
    if report:
        print("Character update — " + " | ".join(report) + ". Details: notes/characters/<slug>/summary.md")
    elif not quiet:
        print(f"No changes (or snapshots fresh <{core.THROTTLE_HOURS}h). Use --force to refetch.")
    if hook:
        print(hook_instructions(chars, hook_session_id()))
        for slug, v in core.failing().items():
            print(f"⚠ armory parsing looks broken for {slug} since {v['failing_since'][:10]} ({'; '.join(v['problems'])}). "
                  f"Run: python3 \"{core.SCRIPT}\" doctor {slug} and show the user the failing step.")
        ms = []
        for c in core.owned(chars):
            h = core.history(c["slug"], tail=8000)
            if h:
                got = milestones.announce(c["slug"], h[-1], core.version_of(c))
                if got:
                    ms.append(f"{c['name']}: " + "; ".join(got))
        if ms:
            print("Milestones reached (remind the user once at the start of your reply, then log what they train): " + " | ".join(ms))
        news = friend_news(chars)
        if news:
            print("Friend news (mention in one short line; don't log it): " + " | ".join(news))
    pend = pending_report()
    if pend:
        print("Since last recap (open your first reply with a 2–3 line 'last time' summary and ask the open questions):\n" + "\n".join(pend))


def hook_session_id():
    """session_id from the SessionStart hook's JSON on stdin, or None (run by hand, or no JSON)."""
    try:
        if sys.stdin is None or sys.stdin.isatty():
            return None
        return (json.loads(sys.stdin.read() or "{}") or {}).get("session_id")
    except Exception:
        return None


def session_focus(session_id):
    """The slug pinned with focus for this session (or for all sessions), else None."""
    f = core.read_json(core.BASE / ".focus.json", None) or {}
    if f.get("slug") and (not f.get("session_id") or f["session_id"] == session_id):
        return f["slug"]
    return None


def hook_instructions(chars, session_id=None):
    mine = core.owned(chars)
    mine.sort(key=lambda c: not c.get("main"))
    who = ", ".join(f'{c["name"]} ({c["slug"]})' + (" [main: the user's favorite; assume it unless context points elsewhere]" if c.get("main") else "") for c in mine) or "no owned characters"
    lines = [f"WoW character tracking (wow-waypoint) is on for {who}. Script: python3 \"{core.SCRIPT}\" (data in {core.BASE}); type the full command each time, never via a shell variable (zsh won't split it)."]
    focus = session_focus(session_id)
    fc = next((c for c in mine if c["slug"] == focus), None)
    if fc and not fc.get("main"):
        lines.append(f"- Session focus: {fc['name']} ({fc['slug']}) is pinned for this session; assume it here instead of the primary.")
    if len(mine) > 1:
        sid = f" --session {session_id}" if session_id else " --session <this session's id>"
        lines.append("- Main vs focus: main = the user's favorite and default; never change it to switch characters. "
                     "When context points to another character (\"my warlock\"), answer for that one. When they stay on it for a stretch "
                     f"(said so, or a second question in a row), pin it for this session: focus <slug>{sid} (one line to them); "
                     "switch again or focus --clear when they move back to main. Unnamed questions follow the current pin.")
    if watched := core.watched(chars):
        lines.append(f"- Watched friends ({len(watched)}): " + ", ".join(c["name"] for c in watched) + ". Use `party` for the group; never log their activity.")
    if (pl := core.profile_line(core.load_profile())):
        lines.append("- " + pl)
    lines += [
        "- For questions about gear, upgrades or progress, read notes/characters/<slug>/summary.md first.",
        "- When a message reveals play (zone, quest, dungeon, loot, purchase, training, talents, a plan), silently append one "
        "factual line: log <slug> \"...\". If an outcome that matters is unknown, log it with a leading \"?\" and ask at a natural pause "
        "(at most 1-3 at a time); once answered, rewrite that line in activity.md without the \"?\". Skip pure lookups.",
        "- If the user says they just logged out, run update --force. If they mention a new character, offer to add it.",
        "- Skills: `wow-help` (feature overview), `track` (commands, rules), `wow-init` (setup), `recap`, `plan`, `instance` (role briefing before a dungeon or raid), `party`, `dashboard`.",
    ]
    return "\n".join(lines)


def friend_news(chars):
    marker = core.BASE / ".last_session"
    since = marker.read_text().strip() if marker.exists() else None
    out = []
    if since:
        for c in core.watched(chars):
            h = core.history(c["slug"])
            before = [s for s in h if s["at"] <= since]
            if before and h[-1]["at"] > since:
                d = [x for x in core.diff(before[-1], h[-1], with_milestones=False) if not x.startswith(("quests", "kills"))]
                if d:
                    out.append(f"{c['name']}: " + "; ".join(d[:4]) + (" …" if len(d) > 4 else ""))
    if core.BASE.exists():
        core.write_text(marker, core.now().isoformat(timespec="seconds"))
    return out


def cmd_add(args):
    region = opt(args, "--region", "us")
    version = opt(args, "--version", "forever")
    name = " ".join(positional(args))
    if not name:
        sys.exit('usage: add "First Last" [--region us] [--version forever] [--watch] [--group NAME] [--role tank,dps] [--main]')
    slug = core.slugify(name)
    chars = core.load_config()
    if any(c["slug"] == slug for c in chars):
        print(f"{slug} already tracked (use `set {slug} key=value` to change it)")
        return
    entry = {"region": region, "slug": slug, "name": name}
    if version != "forever":
        entry["version"] = version
    for flag, key in (("--group", "group"), ("--source", "source")):
        if opt(args, flag):
            entry[key] = opt(args, flag)
    if "--watch" in args:
        entry["watch"] = True
    if opt(args, "--role"):
        entry["roles"] = [r.strip() for r in opt(args, "--role").split(",") if r.strip()]
    if "--main" in args:
        entry["main"] = True
    try:
        norm, problems = sources.fetch(entry, core.data("sources"))
    except sources.Unsupported as e:
        chars.append(entry)
        core.save_config(chars)
        print(f"Saved {name} ({core.version_info(entry).get('label')}), but {e}. Q&A and planning still work; snapshots start once a source exists.")
        return
    except (sources.NetworkError, sources.ParseError) as e:
        sys.exit(f"could not fetch {name}: {e}")
    entry["name"] = norm["name"]
    chars.append(entry)
    core.save_config(chars)
    snap, _ = store_snapshot(entry, norm)
    core.record_health(slug, problems)
    what = "Watching" if entry.get("watch") else "Tracking"
    print(f"{what} {snap['name']}: level {snap['level']} {snap['race']} {snap['class']} ({snap['faction']}, {norm.get('realmType') or '?'} realm), "
          f"professions: {', '.join(f'{k} {v}' for k, v in snap['professions'].items()) or 'none'}. See notes/characters/{slug}/summary.md")


def cmd_set(args):
    pos = positional(args)
    if len(pos) < 2:
        sys.exit("usage: set <char> key=value ...")
    chars = core.load_config()
    c = core.find_char(pos[0], chars) or need_char(pos[0])
    for kv in pos[1:]:
        k, v = core.parse_assignment(kv)
        if v is None:
            c.pop(k, None)
        else:
            c[k] = v
    core.save_config(chars)
    print(json.dumps(c))


def cmd_main(args):
    """main <char> makes it the primary character (clears the flag on the others); main alone shows it.

    main = the user's favorite and the default everywhere. It is long-lived: change it only when the user says their
    favorite changed. To play another character for a while, use `focus <char> --session ID` instead."""
    chars = core.load_config()
    pos = positional(args)
    if not pos:
        p = core.primary(chars)
        print(f"primary: {p['name']} ({p['slug']})" if p else "no primary set; defaults to most recently played")
        return
    c = core.find_char(pos[0], chars) or need_char(pos[0])
    if c.get("watch"):
        sys.exit(f"{c['name']} is a watched friend, not yours")
    for x in chars:
        x.pop("main", None)
    c["main"] = True
    core.save_config(chars)
    print(f"primary character is now {c['name']} ({c['slug']}); to switch for one session instead, use focus <char> --session ID")


